// coordinatesPanel offers precise authored position and heading values.
func (work *Workspace) coordinatesPanel() widget.Widget {
	object, ok := work.selectedObject()
	if !ok {
		return work.text("Choose an authored object.")
	}
	at := object.Position()
	heading, said := object.Heading()
	if work.play.poseObject != object.ID() || work.play.poseSource != work.state.document.Text() {
		work.play.poseObject, work.play.poseSource = object.ID(), work.state.document.Text()
		for i, value := range at {
			work.play.poseText[i] = strconv.FormatFloat(value, 'f', -1, 64)
		}
		work.play.poseText[3] = strconv.FormatFloat(heading, 'f', -1, 64)
		if object.Grounded() && !said {
			work.play.poseText[3] = ""
		}
	}
	labels := []string{"East (m)", "North (m)", "Up (m)", "Heading (degrees)"}
	if object.Grounded() {
		labels[2] = "Above ground (m)"
	}
	count := 4
	if object.Grounded() && !said {
		count = 3
	}
	var fields [4]*textfield.Widget
	items := []widget.Widget{work.text(object.Name())}
	for i := 0; i < count; i++ {
		index := i
		field := textfield.New(textfield.InitialValue(work.play.poseText[index]), textfield.A11yLabel(labels[index]), textfield.PainterOpt(appearance.TextFieldPainter{Size: work.size}), textfield.OnChange(func(text string) { work.play.poseText[index] = text }))
		field.SetID(labels[index])
		fields[index] = field
		items = append(items, work.text(labels[index]), field)
	}
	if count == 3 {
		items = append(items, work.generatedHeadingControl())
	}
	apply := work.action("Set coordinates", true, func() bool { return false }, func() {
		for i := 0; i < count; i++ {
			work.play.poseText[i] = fields[i].Text()
		}
		work.problem(work.submitCoordinates(count == 4))
	})
	items = append(items, apply)
	return primitives.VBox(items...).Gap(8)
}

func (work *Workspace) submitGeneratedHeading(text string) error {
	if err := work.fullRenderRefusal("changing the scene"); err != nil {
		return err
	}
	object, ok := work.selectedObject()
	if !ok {
		return fmt.Errorf("choose an authored object")
	}
	degrees, err := strconv.ParseFloat(strings.TrimSpace(text), 64)
	if err != nil || math.IsNaN(degrees) || math.IsInf(degrees, 0) {
		return fmt.Errorf("enter a finite heading in degrees")
	}
	if err := work.state.document.SetGeneratedHeading(object.ID(), degrees); err != nil {
		return err
	}
	work.stopPreview()
	work.editor.ApplyText(work.state.document.Text())
	work.needsCheck = false
	work.working.dirty = true
	work.play.poseObject = ""
	work.caption = "Heading changed · working view updating"
	work.status = "Heading changed · ⌘Z to undo"
	work.diagnostic = ""
	work.refreshLayout = true
	work.invalidate()
	return nil
}

func (work *Workspace) generatedHeadingControl() widget.Widget {
	field := textfield.New(textfield.InitialValue(work.play.poseText[3]), textfield.A11yLabel("New heading (degrees)"), textfield.PainterOpt(appearance.TextFieldPainter{Size: work.size}), textfield.OnChange(func(text string) { work.play.poseText[3] = text }))
	field.SetID("New heading (degrees)")
	apply := work.action("Replace generated heading", false, func() bool { return false }, func() {
		work.problem(work.submitGeneratedHeading(field.Text()))
	})
	return primitives.VBox(work.paragraph("Heading is generated by the scene. Choosing an angle replaces it with an authored heading.", appearance.Ink), field, apply).Gap(8)
}

// submitCoordinates makes one checked and undoable source transaction.
func (work *Workspace) submitCoordinates(withHeading bool) error {
	if err := work.fullRenderRefusal("changing the scene"); err != nil {
		return err
	}
	object, ok := work.selectedObject()
	if !ok {
		return fmt.Errorf("choose an authored object")
	}
	var values [4]float64
	count := 3
	if withHeading {
		count = 4
	}
	for i := 0; i < count; i++ {
		n, err := strconv.ParseFloat(strings.TrimSpace(work.play.poseText[i]), 64)
		if err != nil || math.IsNaN(n) || math.IsInf(n, 0) {
			return fmt.Errorf("enter finite coordinates in metres and heading in degrees")
		}
		values[i] = n
	}
	if object.Grounded() {
		if err := work.checkTerrainAddition([3]float64{values[0], values[1], values[2]}); err != nil {
			return err
		}
	}
	at := object.Position()
	delta := draft.PoseChange{ID: object.ID(), East: values[0] - at[0], North: values[1] - at[1], Up: values[2] - at[2], LengthUnit: "m", AngleUnit: "deg"}
	if withHeading {
		current, said := object.Heading()
		if object.Grounded() && !said {
			return fmt.Errorf("this terrain object's heading is generated")
		}
		target := math.Mod(values[3], 360)
		if target < 0 {
			target += 360
		}
		delta.Heading = target - current
	}
	before := work.state.document.Text()
	if err := work.state.document.ChangePose(delta); err != nil {
		return err
	}
	if before == work.state.document.Text() {
		return nil
	}
	work.stopPreview()
	work.editor.ApplyText(work.state.document.Text())
	work.needsCheck = false
	work.working.dirty = true
	work.play.poseObject = ""
	work.caption = "Coordinates changed · working view updating"
	work.status = "Coordinates changed · ⌘Z to undo"
	work.diagnostic = ""
	work.refreshLayout = true
	work.invalidate()
	return nil
}
