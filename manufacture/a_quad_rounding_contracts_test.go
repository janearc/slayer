// exactTriangleCrossSquared interprets the supplied binary64 coordinates as
// exact rationals. It compares area without rounding a square root.
func exactTriangleCrossSquared(a, b, c maths.Vec) *big.Rat {
	values := func(v maths.Vec) [3]*big.Rat {
		return [3]*big.Rat{new(big.Rat).SetFloat64(v.X),
			new(big.Rat).SetFloat64(v.Y), new(big.Rat).SetFloat64(v.Z)}
	}
	aa, bb, cc := values(a), values(b), values(c)
	var u, v [3]*big.Rat
	for i := range 3 {
		u[i] = new(big.Rat).Sub(bb[i], aa[i])
		v[i] = new(big.Rat).Sub(cc[i], aa[i])
	}
	sum := new(big.Rat)
	for i := range 3 {
		j, k := (i+1)%3, (i+2)%3
		cross := new(big.Rat).Sub(new(big.Rat).Mul(u[j], v[k]),
			new(big.Rat).Mul(u[k], v[j]))
		sum.Add(sum, new(big.Rat).Mul(cross, cross))
	}
	return sum
}

func TestQuadKeepsACertifiedDomePoleTriangleAboveItsAreaFloor(t *testing.T) {
	// Generated by the clumps-level dome recipe: 20 sides, side 12, opening 30deg,
	// radius 6.033938143083053e-7m. The second triangle collapses at the
	// pole. Exact rational coordinates put the first above the floor.
	p := [4]maths.Vec{
		maths.V(-1.0155281874295332e-07, 5.738616189901016e-07, 1.5637762755888684e-07),
		maths.V(-1.4178449253735503e-07, 5.738616189901016e-07, 1.2109539657439408e-07),
		maths.V(0, 6.033938143083053e-07, 0),
		maths.V(0, 6.033938143083053e-07, 0),
	}
	limit := new(big.Rat).SetFloat64(1e-14)
	limit.Mul(limit, limit)
	if exactTriangleCrossSquared(p[0], p[1], p[2]).Cmp(limit) <= 0 {
		t.Fatal("fixed dome triangle is not mathematically above the area floor")
	}
	if got := len(quad(nil, p[0], p[1], p[2], p[3])); got != 1 {
		t.Fatalf("certified dome pole kept %d triangles, want one", got)
	}
}
